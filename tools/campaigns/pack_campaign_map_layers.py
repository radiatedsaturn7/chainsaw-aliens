"""Pack terrain plates and editable, per-stop miniature atlases.

Run the miniature painters into a staging directory with one subdirectory per
region slug and stop-*.png files. This packer reads, but never rewrites, the live
menu. Use --output to generate into a separate work directory before review.
"""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path

from PIL import Image
from draw_campaign_terrain import render_terrain

MENU = Path('data/server-storage/files/menus/Game Menu/document.json')
ART = Path('data/server-storage/files/art')
MAP = Path('assets/campaign-art/maps')
TILE = (192, 160)
# Ground motifs (river, cliffs, and painted tracks) carry roads on top.
# Buildings, peaks and signs project in front of the road beyond their base.
# A covered bridge or rock passage sits directly on its route anchor.
GROUND = {
    'providence': {2, 3, 6}, 'mount-washington': {0, 2, 6},
    'laurel-highlands': {2, 3, 6}, 'ohio-river': {0, 3, 4, 6},
    'ozarks': {0, 2, 3, 4, 6, 7}, 'data-center-city': {0, 1, 2, 3, 7},
    'route-66': {0, 3, 6}, 'pikes-peak': {0, 2, 6, 7},
    'moki-dugway': {0, 2, 3, 4, 5, 6}, 'oak-creek-canyon': {1, 2, 3, 6, 7},
    'angeles-crest': {1, 2, 3, 4, 6, 7},
}
UNDER = {'ohio-river': {1, 2}, 'mount-washington': {7}, 'pikes-peak': {1, 3}}
HERO = {'providence': {5, 7}, 'mount-washington': {5},
        'data-center-city': {4, 5}, 'angeles-crest': {0, 5}}

def output(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')

def save(image, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)

def generate(repo, minis, out, revision):
    document = json.loads((repo / MENU).read_bytes())
    screens = {s['id']: s for s in document['screens']}
    manifest = {}
    sprite_hashes = set()
    for i in range(1, 12):
        element = next(e for e in screens[f'campaign-hub-{i}']['elements']
                       if e.get('property') == 'campaign-path')
        ref = element['artRef']
        slug = ref.removeprefix('campaign-map-')
        assert ref.startswith('campaign-map-') and slug in GROUND and ref not in manifest
        native = render_terrain(slug)
        assert native.mode == 'RGB' and native.size == (384, 256)
        png = MAP / f'{ref}.png'
        save(native.resize((1536, 1024), Image.Resampling.NEAREST), out / png)
        source = {'path': png.as_posix(), 'sha256': hashlib.sha256((out / png).read_bytes()).hexdigest(),
                  'width': 1536, 'height': 1024, 'sampling': 'nearest-neighbor', 'maxEdge': 384}
        art = {'kind': 'actor-state-animation', 'width': 384, 'height': 256, 'fps': 1,
               'frames': [['#%02x%02x%02xff' % p for p in native.getdata()]], 'importSource': source}
        data = base64.b64encode(gzip.compress(json.dumps(art, separators=(',', ':')).encode(), mtime=0)).decode()
        output(out / ART / ref / 'document.json',
               json.dumps({'__chainsawStorage': 'compact-v1', 'encoding': 'json-gzip-base64', 'data': data}, indent=2)+'\n')
        metadata = json.loads((repo / ART / ref / 'metadata.json').read_text())
        metadata['savedAt'] = revision
        output(out / ART / ref / 'metadata.json', json.dumps(metadata, indent=2)+'\n')
        board = Image.new('RGBA', (TILE[0]*4, TILE[1]*2))
        entries = {}
        nodes = [n for n in element['nodes'] if n.get('raceRef')]
        assert len(nodes) == 8
        for n in nodes:
            index = int(n['id'].removeprefix('stop-'))
            assert 0 <= index < 8 and n['id'] not in entries
            tile = Image.open(minis / slug / f'{n["id"]}.png')
            assert tile.mode == 'RGBA' and tile.size == TILE
            l,t,r,b = tile.getchannel('A').getbbox()
            assert 0 < l < r < TILE[0] and 0 < t < b < TILE[1]
            sig = hashlib.sha256(tile.tobytes()).hexdigest()
            assert sig not in sprite_hashes
            sprite_hashes.add(sig)
            board.paste(tile, (index%4*TILE[0],index//4*TILE[1]))
            depth = ('underpass' if index in UNDER.get(slug, set()) else
                     'ground' if index in GROUND[slug] else 'raised')
            entries[n['id']] = [n['raceRef'], index, depth, 1.12 if index in HERO.get(slug, set()) else 1]
        save(board, out / 'assets/campaign-map-landmarks' / f'{ref}.png')
        manifest[ref] = dict(sorted(entries.items()))
    assert len(sprite_hashes) == 88
    output(out / 'src/menus/CampaignMapLandmarkLayout.js',
           '// Generated by tools/campaigns/pack_campaign_map_layers.py.\n'
           'export const CAMPAIGN_LANDMARKS = '+json.dumps(manifest, ensure_ascii=False, indent=1)+';\n')

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[2])
    p.add_argument('--minis', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--revision-ms', type=int, required=True)
    a = p.parse_args()
    generate(a.repo, a.minis, a.output, a.revision_ms)
