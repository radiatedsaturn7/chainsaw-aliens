// Keep editor starter tracks in sync with the mapped replacements without
// embedding artwork or expanding thousands of terrain-cell objects at startup.
import fs from 'node:fs';
import zlib from 'node:zlib';
const report=JSON.parse(fs.readFileSync('data/campaigns/america/raceways/report.json'));
const names=['WeatherTech Raceway Laguna Seca','Nurburgring Nordschleife','Col de Turini','Ouninpohja','Daytona Tri-Oval'];
const tracks={};
for(const name of names){
 const entry=report.find(r=>r.status==='imported'&&r.replaceRaceRef===name);
 if(!entry)throw Error(`Missing mapped replacement: ${name}`);
 const r=JSON.parse(fs.readFileSync(entry.generatedPath));
 const stored=JSON.parse(fs.readFileSync(`data/server-storage/files/races/${name}/document.json`));
 const saved=(stored.__chainsawStorage?JSON.parse(zlib.gunzipSync(Buffer.from(stored.data,'base64'))):stored).race;
 for(const key of ['competition','weather','skyboxArtRef','skyboxSettings','roadTextures','groundPlaneArtRef','brightness','visualFx','timeOfDay','margin'])if(saved[key]!==undefined)r[key]=saved[key];
 const tile=r.road.tileMap,coords=Object.keys(tile.cells).map(k=>k.split(',').map(Number));
 const xs=coords.map(c=>c[0]),ys=coords.map(c=>c[1]);
 const minX=Math.min(...xs),maxX=Math.max(...xs),minY=Math.min(...ys),maxY=Math.max(...ys),width=maxX-minX+1,height=maxY-minY+1;
 const bytes=Buffer.alloc(width*height*4);
 for(let y=0;y<height;y++)for(let x=0;x<width;x++)bytes.writeInt32LE(Math.round((tile.cells[`${x+minX},${y+minY}`]?.elevation||0)*1000),(y*width+x)*4);
 delete tile.cells;
 r.source.builtInTerrainPrecisionM=.012;
 tracks[r.id]={race:r,terrain:{minX,minY,width,height,heights:bytes.toString('base64')}};
}
const source=`// Generated by tools/campaigns/update_builtin_tracks.mjs from reviewed OSM/DEM imports.\n// Geometry attribution and snapshot provenance are retained on each race.\nconst tracks=${JSON.stringify(tracks)};\n\nexport function createMappedTestRace(id){\n const data=tracks[id==='laguna-seca'?'weathertech-raceway':id];if(!data)return null;\n const race=structuredClone(data.race),t=data.terrain,raw=atob(t.heights);\n const bytes=Uint8Array.from(raw,c=>c.charCodeAt(0)),view=new DataView(bytes.buffer);\n const cells={};for(let y=0;y<t.height;y++)for(let x=0;x<t.width;x++)cells[(x+t.minX)+','+(y+t.minY)]={tileId:race.road.tileMap.defaultTileId,elevation:view.getInt32((y*t.width+x)*4,true)/1000};\n race.road.tileMap.cells=cells;return race;\n}\n`;
fs.writeFileSync('src/racing/MappedTestTracks.js',source);
console.log(`Updated ${names.length} mapped starter tracks (${Math.round(source.length/1024)} KiB).`);
