// No browser compiler or dependency: regenerate the checked-in JS with Node 24+.
import {stripTypeScriptTypes} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
for(const path of ['src/hardware/wheels/vendor/PidDescriptor','tests/unit/fixtures/pidDescriptor']) {
 const source=readFileSync(`${path}.ts`,'utf8');
 const output='// Generated by tools/build-wheel-protocol.mjs; edit the .ts source.\n'+stripTypeScriptTypes(source);
 if(process.argv.includes('--check')) {
  if(readFileSync(`${path}.js`,'utf8')!==output)throw Error(`${path}.js needs regeneration`);
 } else writeFileSync(`${path}.js`,output);
}
